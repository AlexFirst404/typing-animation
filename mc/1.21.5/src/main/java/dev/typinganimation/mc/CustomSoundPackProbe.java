package dev.typinganimation.mc;

import dev.typinganimation.core.BundledSoundResources;
import dev.typinganimation.core.ConfigManager;
import dev.typinganimation.core.CustomSoundPackLibrary;
import dev.typinganimation.core.TypingConfig;
import dev.typinganimation.core.TypingSoundAction;
import net.minecraft.client.Minecraft;
import net.minecraft.resources.ResourceLocation;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.concurrent.CompletableFuture;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/** Runtime probe: installs only its own generated test pack and restores the user's configuration. */
public final class CustomSoundPackProbe {
    private static String importedId;
    private static TypingConfig previous;
    private CustomSoundPackProbe() { }

    public static CompletableFuture<Void> prepare() throws Exception {
        if (previous != null) throw new IllegalStateException("Sound library probe already prepared");
        previous = ConfigManager.get().copy();
        Path archive = Files.createTempFile("typinganimation-sound-probe-", ".zip");
        try {
            try (ZipOutputStream zip = new ZipOutputStream(Files.newOutputStream(archive))) {
                zip.putNextEntry(new ZipEntry("pack.json"));
                String manifest = "{\"format\":1,\"name\":\"Self-test " + java.util.UUID.randomUUID()
                        + "\",\"sounds\":{\"key\":\"key.ogg\",\"space\":\"space.ogg\",\"backspace\":\"backspace.ogg\",\"enter\":\"enter.ogg\"}}";
                zip.write(manifest.getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
                for (TypingSoundAction action : TypingSoundAction.values()) {
                    zip.putNextEntry(new ZipEntry(action.path() + ".ogg"));
                    try (var input = BundledSoundResources.open("sounds/typing/soft/" + action.path() + "_1.ogg")) {
                        input.transferTo(zip);
                    }
                    zip.closeEntry();
                }
            }
            var imported = CustomSoundPackLibrary.defaultLibrary().importPack(archive);
            if (!imported.success()) throw new IllegalStateException("Probe pack import failed: " + imported.message());
            importedId = imported.pack().id();
        } finally { Files.deleteIfExists(archive); }
        TypingConfig cfg = ConfigManager.get();
        cfg.customSoundPack = importedId;
        cfg.typingSounds = true;
        cfg.soundVolume = .15f;
        cfg.adaptiveTyping = false;
        cfg.soundVariation = false;
        return TypingSounds.reloadCustomPacks();
    }

    /** Call after prepare's future completes, on the Minecraft client thread with a screen open. */
    public static void verifyLoadedAndPlay() {
        if (importedId == null || !ClasspathSoundPack.customAvailable(importedId))
            throw new AssertionError("Imported sound pack was not registered");
        Minecraft mc = Minecraft.getInstance();
        for (TypingSoundAction action : TypingSoundAction.values()) {
            var event = ResourceLocation.fromNamespaceAndPath(CustomSoundPackLibrary.NAMESPACE, CustomSoundPackLibrary.eventPath(importedId, action));
            var sound = mc.getSoundManager().getSoundEvent(event);
            if (sound == null || sound.getWeight() <= 0) throw new AssertionError("Imported sound event not loaded: " + event);
        }
        for (String path : CustomSoundPackLibrary.defaultLibrary().resources().keySet()) {
            var resource = ResourceLocation.fromNamespaceAndPath(CustomSoundPackLibrary.NAMESPACE, path);
            if (mc.getResourceManager().getResource(resource).isEmpty()) throw new AssertionError("Missing imported resource: " + path);
        }
        TypingSounds.resetTestCounters();
        TypingSounds.previewCustom(importedId);
        if (TypingSounds.playedCount != 1 || !importedId.equals(TypingSounds.lastCustomPack))
            throw new AssertionError("Audition did not select the imported sound pack");
        if (TypingSounds.firstError != null) throw new AssertionError("Imported playback failure", TypingSounds.firstError);
    }

    /** Failure-path cleanup, before the outer self-test restores its original configuration and stops the client. */
    public static void abort() {
        try {
            if (previous != null) ConfigManager.get().copyFrom(previous);
            if (importedId != null) CustomSoundPackLibrary.defaultLibrary().deletePack(importedId);
        } catch (RuntimeException ignored) { }
        previous = null;
        importedId = null;
    }

    /** Only deletes the pack generated by prepare(); never touches an existing user pack. */
    public static CompletableFuture<Void> cleanup() {
        if (previous != null) ConfigManager.get().copyFrom(previous);
        previous = null;
        if (importedId != null) {
            var deleted = CustomSoundPackLibrary.defaultLibrary().deletePack(importedId);
            if (!deleted.success()) throw new IllegalStateException("Probe pack cleanup failed: " + deleted.message());
        }
        importedId = null;
        return TypingSounds.reloadCustomPacks();
    }
}
